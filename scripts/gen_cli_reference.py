def first_sentence(cmd: click.Command) -> str:
    """The first paragraph of the command's own help, on one line.

    Read from the help text itself rather than Click's short help, which
    differs between Click versions (8.1 cuts at the first full stop, so an
    "e.g." ends it), so every machine writes the same page."""
    if cmd.short_help:
        text = cmd.short_help
    else:
        doc = inspect.cleandoc(cmd.help or "").split("\f", 1)[0]
        lines = [ln for ln in doc.splitlines() if ln.strip() != "\b"]
        text = "\n".join(lines).strip().split("\n\n", 1)[0]
    return " ".join(text.split()).replace("|", "\\|")


def walk(group: click.Group, path: list[str]):
    ctx = click.Context(group, info_name=path[-1])
    for name in sorted(group.list_commands(ctx)):
        cmd = group.get_command(ctx, name)
        if cmd is None or getattr(cmd, "hidden", False):
            continue
        yield path + [name], cmd
        if isinstance(cmd, click.Group):
            yield from walk(cmd, path + [name])


def render() -> str:
    from nomad import __version__
    from nomad.cli import cli

    rows = list(walk(cli, ["nomad"]))
    top = [(p, c) for p, c in rows if len(p) == 2]
    out = [
        "# All commands",
        "",
        "<!-- Generated by scripts/gen_cli_reference.py from the CLI's own help: do not edit by hand. -->",
        "",
        f"Every `nomad` command in {__version__}, each with the first line of its own",
        "`--help`. `nomad COMMAND --help` has its options and examples; the page",
        "named beside each command explains it. The [CLI Reference](cli.md) has the",
        "common ones with their usual options.",
        "",
        "| Command | What it does |",
        "|---|---|",
    ]
    def has_subs(p):
        return any(sp[:2] == p and len(sp) > 2 for sp, _ in rows)

    for p, c in top:
        page = DOCS.get(p[1])
        link = f" ([docs]({page}))" if page else ""
        name = f"[`{' '.join(p)}`](#{p[1]})" if has_subs(p) else f"`{' '.join(p)}`"
        out.append(f"| {name} | {first_sentence(c)}{link} |")
    out.append("")
    for p, c in top:
        if not isinstance(c, click.Group):
            continue
        subs = [(sp, sc) for sp, sc in rows if sp[:2] == p and len(sp) > 2]
        if not subs:
            continue
        page = DOCS.get(p[1])
        out += [f"## {p[1]}", ""]
        out.append(first_sentence(c) + (f" See [{page}]({page})." if page else ""))
        out += ["", "| Command | What it does |", "|---|---|"]
        for sp, sc in subs:
            sub_page = SUB_DOCS.get(tuple(sp[1:3]))
            link = f" ([docs]({sub_page}))" if sub_page and len(sp) == 3 else ""
            out.append(f"| `{' '.join(sp)}` | {first_sentence(sc)}{link} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/cli-commands.md is out of date")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    text = render()
    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is out of date: run python scripts/gen_cli_reference.py", file=sys.stderr)
            return 1
        return 0
    args.out.write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
